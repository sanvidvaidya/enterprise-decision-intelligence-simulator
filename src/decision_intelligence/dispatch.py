"""Action Dispatch Bridge & Execution Engine.

Dispatches recommended interventions and risk alerts to external execution
channels (Webhooks, Slack alerts, CRM/Linear tasks, and Email) with end-to-end
audit logging and closed-loop status updates.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from datetime import datetime, timezone
import json
from pathlib import Path
from typing import Any, Dict, List, Optional
import urllib.request
import urllib.error
import uuid

from decision_intelligence.causal import extract_customer_causal_state
from decision_intelligence.database import DEFAULT_DATABASE_PATH, connect
from decision_intelligence.risk_engine import assess_customer


@dataclass
class DispatchRecord:
    """Audit log entry for an executed or simulated action dispatch."""

    dispatch_id: str
    customer_id: str
    action_id: Optional[str]
    channel: str
    destination: str
    status: str
    response_code: Optional[int]
    error_message: Optional[str]
    payload: Dict[str, Any]
    dispatched_at: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


def ensure_dispatch_table(conn) -> None:
    """Ensure the action_dispatches audit table exists."""
    conn.execute(
        """CREATE TABLE IF NOT EXISTS action_dispatches (
               dispatch_id TEXT PRIMARY KEY,
               customer_id TEXT NOT NULL,
               action_id TEXT,
               channel TEXT NOT NULL,
               destination TEXT NOT NULL,
               status TEXT NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SIMULATED')),
               response_code INTEGER,
               error_message TEXT,
               payload_json TEXT NOT NULL,
               dispatched_at TEXT NOT NULL,
               FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
               FOREIGN KEY (action_id) REFERENCES account_actions(action_id)
           )"""
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_dispatches_customer ON action_dispatches(customer_id)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_dispatches_date ON action_dispatches(dispatched_at)"
    )
    conn.commit()


def _format_slack_payload(customer: dict, assessment: dict, action_text: str, owner: str) -> dict:
    """Build Slack Block Kit notification payload."""
    score = assessment["risk_score"]
    level = assessment["risk_level"]
    emoji = "🚨" if level == "High" else "⚠️" if level == "Medium" else "✅"

    return {
        "text": f"{emoji} Renewal Risk Alert: {customer['customer_name']} is at {level} Risk ({score}/100)",
        "blocks": [
            {
                "type": "header",
                "text": {
                    "type": "plain_text",
                    "text": f"{emoji} Renewal Risk Alert: {customer['customer_name']}",
                    "emoji": True,
                },
            },
            {
                "type": "section",
                "fields": [
                    {"type": "mrkdwn", "text": f"*Risk Level:*\n`{level}` ({score}/100)"},
                    {"type": "mrkdwn", "text": f"*Annual Contract Value:*\n${customer.get('annual_contract_value', 0):,.2f}"},
                    {"type": "mrkdwn", "text": f"*Renewal Date:*\n{customer.get('renewal_date', 'N/A')}"},
                    {"type": "mrkdwn", "text": f"*Account Owner:*\n{owner or customer.get('account_manager_name', 'Unassigned')}"},
                ],
            },
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": f"*Recommended Intervention:*\n>{action_text}",
                },
            },
            {
                "type": "context",
                "elements": [
                    {
                        "type": "mrkdwn",
                        "text": f"Generated by Enterprise Decision Simulator • {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
                    }
                ],
            },
        ],
    }


def _format_crm_task_payload(customer: dict, assessment: dict, action_text: str, owner: str) -> dict:
    """Build structured CRM / Linear / Jira task payload."""
    return {
        "task_type": "churn_prevention_intervention",
        "title": f"Intervention Required: {customer['customer_name']} ({assessment['risk_level']} Risk)",
        "priority": "High" if assessment["risk_level"] == "High" else "Medium",
        "customer_id": customer["customer_id"],
        "customer_name": customer["customer_name"],
        "assignee_email": customer.get("account_manager_email", owner),
        "due_date": datetime.now(timezone.utc).date().isoformat(),
        "description": (
            f"Automated Decision Support Action Item.\n\n"
            f"Customer: {customer['customer_name']} (ACV: ${customer.get('annual_contract_value', 0):,.2f})\n"
            f"Risk Score: {assessment['risk_score']} ({assessment['risk_level']})\n"
            f"Action: {action_text}\n"
        ),
        "tags": ["renewal-risk", "automated-dispatch", assessment["risk_level"].lower()],
    }


def _format_webhook_payload(customer: dict, assessment: dict, action_text: str, owner: str, custom_data: dict | None) -> dict:
    """Build canonical webhook event envelope."""
    return {
        "event_id": f"evt-{uuid.uuid4().hex[:12]}",
        "event_type": "decision_intelligence.action_dispatched",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "customer": {
            "customer_id": customer["customer_id"],
            "customer_name": customer["customer_name"],
            "industry": customer.get("industry"),
            "segment": customer.get("segment"),
            "annual_contract_value": customer.get("annual_contract_value"),
            "renewal_date": customer.get("renewal_date"),
        },
        "risk_assessment": {
            "score": assessment["risk_score"],
            "level": assessment["risk_level"],
            "factors": [
                {"name": f["name"], "points": f["points"], "action": f["recommended_action"]}
                for f in assessment.get("factors", [])
            ],
        },
        "intervention": {
            "action_text": action_text,
            "owner": owner,
        },
        "custom_data": custom_data or {},
    }


def dispatch_action(
    customer_id: str,
    channel: str,
    destination: Optional[str] = None,
    action_id: Optional[str] = None,
    action_text: Optional[str] = None,
    owner: Optional[str] = None,
    simulate: bool = True,
    custom_data: Optional[Dict[str, Any]] = None,
    database_path: str | Path = DEFAULT_DATABASE_PATH,
) -> DispatchRecord:
    """Dispatch an intervention action to an external endpoint or queue."""
    channel = channel.lower()
    valid_channels = ("webhook", "slack", "crm_task", "email")
    if channel not in valid_channels:
        raise ValueError(f"Invalid channel '{channel}'. Supported: {', '.join(valid_channels)}")

    with connect(database_path) as conn:
        ensure_dispatch_table(conn)

        # Retrieve customer context
        customer_row = conn.execute(
            """SELECT c.*, am.full_name AS account_manager_name, am.email AS account_manager_email,
                      ct.annual_contract_value, ct.renewal_date
               FROM customers c
               LEFT JOIN account_managers am ON am.account_manager_id = c.account_manager_id
               LEFT JOIN contracts ct ON ct.customer_id = c.customer_id
               WHERE c.customer_id = ?""",
            (customer_id,),
        ).fetchone()

        if not customer_row:
            raise ValueError(f"Customer '{customer_id}' not found.")
        customer = dict(customer_row)

        # Retrieve action text if action_id given
        if action_id:
            action_row = conn.execute(
                "SELECT * FROM account_actions WHERE action_id = ?", (action_id,)
            ).fetchone()
            if action_row:
                action_text = action_text or action_row["action_text"]
                owner = owner or action_row["owner"]

        action_text = action_text or "Execute proactive customer success renewal intervention."
        owner = owner or customer.get("account_manager_name") or "Account Team"

        # Compute current risk assessment
        assessment = assess_customer(customer_id, database_path=database_path)

        # Build channel-specific payload
        if channel == "slack":
            payload = _format_slack_payload(customer, assessment, action_text, owner)
            target = destination or "https://hooks.slack.com/services/simulated-renewal-alerts"
        elif channel == "crm_task":
            payload = _format_crm_task_payload(customer, assessment, action_text, owner)
            target = destination or "internal://crm-task-queue"
        elif channel == "webhook":
            payload = _format_webhook_payload(customer, assessment, action_text, owner, custom_data)
            target = destination or "https://api.example.com/webhooks/renewal-risk"
        else: # email
            payload = {
                "to": customer.get("account_manager_email", "tam@example.com"),
                "subject": f"URGENT: Renewal Risk Alert for {customer['customer_name']}",
                "body": f"Action required: {action_text}\nRisk Score: {assessment['risk_score']}",
            }
            target = destination or "smtp://mail-gateway"

        dispatch_id = f"disp-{uuid.uuid4().hex[:12]}"
        now_iso = datetime.now(timezone.utc).isoformat()

        # Execute or simulate
        status = "SIMULATED"
        response_code = 200
        error_message = None

        if not simulate:
            if target.startswith("http://") or target.startswith("https://"):
                try:
                    req_data = json.dumps(payload).encode("utf-8")
                    req = urllib.request.Request(
                        target,
                        data=req_data,
                        headers={"Content-Type": "application/json", "User-Agent": "DecisionSimulator/1.0"},
                        method="POST",
                    )
                    with urllib.request.urlopen(req, timeout=5) as resp:
                        response_code = resp.status
                        status = "SENT"
                except urllib.error.HTTPError as e:
                    response_code = e.code
                    status = "FAILED"
                    error_message = f"HTTP Error {e.code}: {e.reason}"
                except Exception as e:
                    response_code = 0
                    status = "FAILED"
                    error_message = str(e)
            else:
                # Internal non-HTTP queue
                status = "SENT"
                response_code = 200

        # Persist audit record
        conn.execute(
            """INSERT INTO action_dispatches (
                   dispatch_id, customer_id, action_id, channel, destination,
                   status, response_code, error_message, payload_json, dispatched_at
               ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (
                dispatch_id,
                customer_id,
                action_id,
                channel,
                target,
                status,
                response_code,
                error_message,
                json.dumps(payload),
                now_iso,
            ),
        )

        # Update account_actions status if applicable
        if action_id:
            conn.execute(
                "UPDATE account_actions SET action_status = 'In Progress' WHERE action_id = ?",
                (action_id,),
            )
            # Log decision event
            event_id = f"de-{uuid.uuid4().hex[:8]}"
            conn.execute(
                """INSERT INTO decision_events (
                       decision_event_id, customer_id, event_type, event_at, actor, notes, related_action_id
                   ) VALUES (?, ?, 'ACTION_DISPATCHED', ?, ?, ?, ?)""",
                (
                    event_id,
                    customer_id,
                    now_iso,
                    f"Dispatcher ({channel})",
                    f"Dispatched intervention via {channel} to {target}",
                    action_id,
                ),
            )

        conn.commit()

        return DispatchRecord(
            dispatch_id=dispatch_id,
            customer_id=customer_id,
            action_id=action_id,
            channel=channel,
            destination=target,
            status=status,
            response_code=response_code,
            error_message=error_message,
            payload=payload,
            dispatched_at=now_iso,
        )


def list_dispatch_history(
    customer_id: Optional[str] = None,
    limit: int = 50,
    database_path: str | Path = DEFAULT_DATABASE_PATH,
) -> List[Dict[str, Any]]:
    """Retrieve history of dispatched actions with payloads."""
    with connect(database_path) as conn:
        ensure_dispatch_table(conn)
        if customer_id:
            rows = conn.execute(
                """SELECT * FROM action_dispatches
                   WHERE customer_id = ?
                   ORDER BY dispatched_at DESC LIMIT ?""",
                (customer_id, limit),
            ).fetchall()
        else:
            rows = conn.execute(
                """SELECT * FROM action_dispatches
                   ORDER BY dispatched_at DESC LIMIT ?""",
                (limit,),
            ).fetchall()

        results = []
        for r in rows:
            d = dict(r)
            try:
                d["payload"] = json.loads(d.pop("payload_json"))
            except Exception:
                d["payload"] = {}
            results.append(d)
        return results
